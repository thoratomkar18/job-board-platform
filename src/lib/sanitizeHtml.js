/**
 * Lightweight HTML sanitizer to prevent Stored XSS in rich descriptions.
 * Strips script tags, iframe, object, embed, event handlers, and javascript: protocols.
 */
export const sanitizeHtml = (dirty = '') => {
  if (!dirty || typeof dirty !== 'string') return '';

  return dirty
    // Remove script tags and contents
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    // Remove inline event handlers (onload, onerror, onclick, etc.)
    .replace(/\son\w+\s*=\s*(['"]).*?\1/gi, '')
    .replace(/\son\w+\s*=\s*[^>\s]+/gi, '')
    // Remove dangerous URI schemes
    .replace(/href\s*=\s*(['"])\s*javascript:[^'"]*\1/gi, 'href="#"')
    .replace(/src\s*=\s*(['"])\s*javascript:[^'"]*\1/gi, 'src="#"')
    // Remove iframes, objects, embeds
    .replace(/<iframe\b[^<]*(?:(?!<\/iframe>)<[^<]*)*<\/iframe>/gi, '')
    .replace(/<object\b[^<]*(?:(?!<\/object>)<[^<]*)*<\/object>/gi, '')
    .replace(/<embed\b[^>]*>/gi, '');
};
